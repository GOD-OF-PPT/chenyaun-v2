  function getArtDecodeSummarySnapshot() {
    const keys = Object.keys(ART);
    const decoded = [];
    const failed = [];
    for (const k of keys) {
      const im = IMG_CACHE[k];
      if (im && im.complete && im.naturalWidth > 0 && im.naturalHeight > 0) {
        decoded.push({ key: k, w: im.naturalWidth, h: im.naturalHeight });
      } else {
        failed.push({ key: k, complete: Boolean(im && im.complete), w: im ? im.naturalWidth : 0, h: im ? im.naturalHeight : 0 });
      }
    }
    return { total: keys.length, decodedCount: decoded.length, decoded, failed };
  }

